CREATE TABLE IF NOT EXISTS `servers`
(
  `id` INT(255) UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `build_dockerfile` VARCHAR(1000) NOT NULL DEFAULT '',
  `build_identifier` VARCHAR(255) NOT NULL DEFAULT '',
  `cpu` FLOAT(255,2),
  `ram` INT(255) UNSIGNED,
  `swap` INT(255) UNSIGNED,
  `disk` INT(255) UNSIGNED
);

CREATE TABLE IF NOT EXISTS `server_capadd`
(
  `id` INT(255) UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `server_id` INT UNSIGNED NOT NULL,
  `capability` VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS `server_capdrop`
(
  `id` INT(255) UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `server_id` INT(255) UNSIGNED NOT NULL,
  `capability` VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS `server_buildargs`
(
  `id` INT(255) UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `server_id` INT(255) UNSIGNED NOT NULL,
  `key` VARCHAR(255) NOT NULL,
  `value` VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS `server_backup_exclude`
(
  `id` INT(255) UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `server_id` INT(255) UNSIGNED NOT NULL,
  `exclude` VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS `server_ports`
(
  `id` INT(255) UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `server_id` INT(255) UNSIGNED NOT NULL,
  `internal_port` SMALLINT UNSIGNED NOT NULL,
  `external_port` SMALLINT UNSIGNED NOT NULL,
  `external_ip` VARCHAR(255) NOT NULL,
  `protocol` VARCHAR(255) NOT NULL
);

